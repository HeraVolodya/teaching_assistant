"""Розпізнавання прохань «зроби презентацію / документ / таблицю».

Ціна помилок несиметрична: зайве спрацювання дає файл поруч зі змістом у чаті,
а питання «Як скласти таблицю поправок?» файлом ставати не мусить — інакше
асистент відповідатиме таблицею на кожне друге питання про таблиці стрільби.
"""

from __future__ import annotations

import pytest

from app.export.intent import MAX_SLIDES, DocumentRequest, detect_document_request


@pytest.mark.parametrize(
    ("message", "fmt", "topic"),
    [
        ("Зроби презентацію на 5 слайдів про обов'язки старшого офіцера батареї.",
         "pptx", "обов'язки старшого офіцера батареї"),
        ("Створи документ — короткий конспект для курсантів на тему «Вогнева позиція батареї»",
         "docx", "Вогнева позиція батареї"),
        ("Склади в Excel таблицю видів вогню артилерії з короткими визначеннями.",
         "xlsx", "видів вогню артилерії з короткими визначеннями"),
        ("Підготуй конспект заняття про бойовий порядок батареї", "docx", "бойовий порядок батареї"),
        ("Сформуй таблицю ТТХ гармат", "xlsx", "ТТХ гармат"),
        ("Зробіть слайди про розвідку цілей", "pptx", "розвідку цілей"),
        ("Оформи у вигляді таблиці обов'язки номерів обслуги", "xlsx", "обов'язки номерів обслуги"),
        ("Потрібна презентація про бойовий порядок дивізіону", "pptx", "бойовий порядок дивізіону"),
        ("Можеш скласти таблицю поправок на вітер?", "xlsx", "поправок на вітер"),
        ("Чи можеш створити презентацію про топогеодезичну прив'язку?",
         "pptx", "топогеодезичну прив'язку"),
        ("Склади список обов'язків СОБ в Excel", "xlsx", "список обов'язків СОБ"),
        ("Напиши реферат про історію артилерії", "docx", "історію артилерії"),
        ("Зроби три слайди про ВП", "pptx", "ВП"),
        ("Зроби, будь ласка, коротку презентацію на 7 слайдів про заходи безпеки",
         "pptx", "заходи безпеки"),
        # Адресат — не тема.
        ("Створи конспект для курсантів про вогневу позицію батареї", "docx", "вогневу позицію батареї"),
        ("Підготуй презентацію для курсантів 3 курсу на тему бойовий порядок", "pptx", "бойовий порядок"),
        # Живі написання з першого ж прохання в застосунку (23.11.2026): «ПРИЗЕНТАЦІЮ»
        # тоді не впізналося, і викладач отримав звичайну відповідь без файлу.
        ("ЗРОБИ МЕНІ ПРИЗЕНТАЦІЮ ПРО ОСНОВИ БОЙОВОЇ РОБОТИ", "pptx", "ОСНОВИ БОЙОВОЇ РОБОТИ"),
        ("зроби презинтацію про КСП", "pptx", "КСП"),
        ("Зроби файл презентації про основи бойової роботи", "pptx", "основи бойової роботи"),
    ],
)
def test_requests_are_recognised_with_a_clean_topic(message: str, fmt: str, topic: str) -> None:
    """Тема — без командних слів: «зроби презентацію на 5 слайдів» у пошуковому
    запиті лише шуміло б у BM25 і в ембедингу."""
    request = detect_document_request(message)
    assert request is not None
    assert (request.format, request.topic) == (fmt, topic)


@pytest.mark.parametrize(
    "message",
    [
        "Що таке таблиця стрільби?",
        "Які документи веде старший офіцер батареї?",
        "Як скласти таблицю поправок?",
        "Наведи приклад таблиці стрільби",
        "Розкажи про документ «Бойовий статут»",
        "Зроби висновок з таблиці 3",
        "Що треба зробити, щоб скласти таблицю стрільби?",
        "Чи можна скласти таблицю без метеобюлетеня?",
        "Не роби таблицю, просто поясни",
        "Як зробити презентацію в PowerPoint?",
        "Створи план стрільби",
        "Що таке деривація снаряда?",
        "Склади бойове розпорядження",
        "Зроби короткий висновок",
        "Що таке призентація?",
        "",
    ],
)
def test_questions_stay_questions(message: str) -> None:
    assert detect_document_request(message) is None


def test_program_name_wins_over_the_noun() -> None:
    """«Таблицю у Word» — це документ Word, головне в якому таблиця."""
    request = detect_document_request("Зроби таблицю у Word про види вогню")
    assert request == DocumentRequest(format="docx", topic="види вогню", table=True)


def test_plain_document_is_not_a_table() -> None:
    request = detect_document_request("Створи документ про види вогню")
    assert request is not None and request.format == "docx" and not request.table


def test_noun_used_as_topic_is_kept_in_the_topic() -> None:
    """Вирізається лише та назва формату, що визначила формат: конспект ПРО
    таблиці стрільби мусить шукати таблиці стрільби."""
    request = detect_document_request("Склади конспект про таблиці стрільби")
    assert request is not None
    assert (request.format, request.topic) == ("docx", "таблиці стрільби")


@pytest.mark.parametrize(
    ("message", "slides"),
    [
        ("Зроби презентацію на 5 слайдів про КСП", 5),
        ("Зроби 10 слайдів про маскування вогневих позицій", 10),
        ("Зроби презентацію на п'ять слайдів про КСП", 5),
        ("Зроби презентацію на п’ять слайдів про КСП", 5),     # типографський апостроф
        ("Зроби презентацію на 8–10 слайдів про КСП", 10),
        ("Зроби презентацію на 40 слайдів про КСП", MAX_SLIDES),
        ("Зроби презентацію про КСП", None),
    ],
)
def test_slide_count(message: str, slides: int | None) -> None:
    request = detect_document_request(message)
    assert request is not None and request.slides == slides
    assert "слайд" not in request.topic


@pytest.mark.parametrize(
    "message",
    ["Зроби з цього презентацію", "Збережи цю відповідь у Word", "Експортуй у ексель",
     "Оформи це як таблицю",
     # Друге живе прохання: темою тоді ставало «ФАЙЛ ПРИЗЕНТАЦІЇ», а не попереднє питання.
     "ТЕПЕР ЗРОБИ МЕНІ ФАЙЛ ПРИЗЕНТАЦІЇ PPTX"],
)
def test_reference_to_the_previous_answer_has_no_topic(message: str) -> None:
    """Порожня тема — сигнал чатові взяти тему попереднього питання."""
    request = detect_document_request(message)
    assert request is not None and request.topic == ""


def test_topic_from_a_neighbouring_sentence() -> None:
    request = detect_document_request("Що таке СОБ? Зроби про це презентацію.")
    assert request is not None
    assert request.format == "pptx" and "СОБ" in request.topic
