def is_known_word(token: str) -> bool:
    """Чи є токен словниковим — точно або за основою.

    Префіксне зіставлення йде від довшого до коротшого, мінімум MIN_STEM:
    коротші префікси дають забагато хибних влучань і поріг перестає працювати.
    """
    if token in STOPWORDS or token in LEXICON_WORDS:
        return True
    upper = min(len(token), 12)
    return any(token[:k] in LEXICON_STEMS for k in range(upper, MIN_STEM - 1, -1))


def lexicon_hit_rate(tokens: list[str], *, min_tokens: int = 12) -> float | None:
    """Частка словникових слів серед кириличних токенів довжиною >= 3.

    Повертає None, коли кириличних токенів менше за `min_tokens`: на порожній
    або суто табличній сторінці статистика недостовірна, і хибне спрацювання
    коштувало б повного OCR цілком доброї сторінки.
    """
    eligible = [
        t for t in tokens
        if len(t) >= 3 and sum(1 for ch in t if is_cyrillic(ch)) * 2 >= len(t)
    ]
    if len(eligible) < min_tokens:
        return None
    hits = sum(1 for t in eligible if is_known_word(t))
    return hits / len(eligible)
