const FALLBACK: Omit<ErrorDescription, "code"> = {
  title: "Обробку не завершено",
  explain: "Застосунок не зміг довести обробку цього матеріалу до кінця.",
  action: "retry",
  actionLabel: "Повторити обробку",
};

export function describeError(code: string | null | undefined): ErrorDescription {
  const key = (code ?? "").trim().toUpperCase();
  const entry = TABLE[key] ?? FALLBACK;
  return { code: key || "UNKNOWN", ...entry };
}

export function isKnownErrorCode(code: string | null | undefined): boolean {
  return Boolean(code && code.trim().toUpperCase() in TABLE);
}

/**
 * Текст для кнопки «Копіювати діагностику».
 *
 * ВМІСТУ МАТЕРІАЛІВ ТУТ НЕМАЄ І НЕ БУДЕ. Назва документа включається лише
 * за явним дозволом: це військова академія, і сам перелік завантажених
 * підручників уже є інформацією (реєстр ризиків плану).
 */
export function diagnosticsText(input: {
  code: string | null | undefined;
  detail?: string | null;
  documentTitle?: string | null;
  includeTitle: boolean;
  appVersion?: string;
  platform?: string;
  stage?: string | null;
  at?: Date;
}): string {
  const described = describeError(input.code);
  const lines = [
    "Асістент — діагностика помилки обробки",
    `Час: ${(input.at ?? new Date()).toISOString()}`,
    `Версія: ${input.appVersion ?? "невідомо"}`,
    `Платформа: ${input.platform ?? "невідомо"}`,
    `Код: ${described.code}`,
    `Етап: ${input.stage ?? "невідомо"}`,
    `Опис: ${described.title}`,
  ];
  if (input.detail) lines.push(`Деталі: ${input.detail}`);
  lines.push(
    input.includeTitle && input.documentTitle
      ? `Матеріал: ${input.documentTitle}`
      : "Матеріал: назву приховано за налаштуванням приватності",
  );
  return lines.join("\n");
}
