/**
 * Помилки індексації: код → що сталося, ЧОМУ і що з цим робити.
 *
 * Одне повідомлення «Індексація не вдалась» коштує дорожче за всі інші
 * помилки разом: воно не дає викладачеві жодного наступного кроку, тож
 * єдине, що він може зробити, — покликати розробника. Тому кожен код тут
 * має три обов'язкові частини: людський заголовок, пояснення причини
 * побутовою мовою (без «парсера», «чанків» і «ембедингів») і КНОПКУ ДІЇ.
 *
 * Коди — ті самі рядки, що їх пише `documents.error_code`
 * (`app/jobs/runner.py`) плюс коди рівня API. Невідомий код не має ламати
 * екран: `describeError` завжди повертає щось осмислене.
 */

/** Що саме UI намалює як головну кнопку. */
export type ErrorAction =
  | "retry" // повторити обробку в тому самому режимі
  | "retry-deep" // повторити в поглибленому режимі (VLM-ремонт сторінок)
  | "remove" // прибрати документ із бази
  | "reupload" // завантажити файл заново
  | "open-lmstudio" // перейти до налаштувань мовної моделі
  | "open-setup" // майстер першого запуску: бракує файлів моделей
  | "none";

export interface ErrorDescription {
  code: string;
  title: string;
  /** Причина людською мовою. Одне-два речення, без жаргону. */
  explain: string;
  action: ErrorAction;
  actionLabel: string;
  /** Другорядна підказка — те, що викладач може зробити руками. */
  hint?: string;
  /** true → це не збій, а свідома дія користувача; фарбувати нейтрально. */
  benign?: boolean;
}

